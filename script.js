const reviewForm = document.querySelector("#review-form");
const reviewsGrid = document.querySelector(".reviews-grid");
const reviewFormStatus = document.querySelector("#review-form-status");
const reviewsStorageKey = "u-josefa-reviews";
const ratingScore = document.querySelector(".rating-score > strong");
const ratingScoreStars = document.querySelector(".rating-score-stars");
const ratingCountText = document.querySelector(".rating-score > p");
const reviewsCountText = document.querySelector(".reviews-list-heading > span");
const ratingRows = document.querySelectorAll(".rating-breakdown .rating-row");

if (
  reviewForm instanceof HTMLFormElement
  && reviewsGrid instanceof HTMLElement
  && reviewFormStatus instanceof HTMLElement
) {
  const nameInput = reviewForm.querySelector("#review-name");
  const ratingSelect = reviewForm.querySelector("#review-rating");
  const textInput = reviewForm.querySelector("#review-text");

  const isReview = (value) => (
    typeof value === "object"
    && value !== null
    && typeof value.name === "string"
    && value.name.trim().length > 0
    && Number.isInteger(value.rating)
    && value.rating >= 1
    && value.rating <= 5
    && typeof value.text === "string"
    && value.text.trim().length > 0
    && typeof value.date === "string"
    && !Number.isNaN(Date.parse(value.date))
  );

  const createReviewCard = (review) => {
    const card = document.createElement("article");
    card.className = "review-card";
    card.dataset.rating = String(review.rating);

    const header = document.createElement("header");
    header.className = "review-card-header";

    const person = document.createElement("div");
    person.className = "review-person";

    const avatar = document.createElement("span");
    avatar.className = "review-avatar";
    avatar.setAttribute("aria-hidden", "true");
    const initials = review.name.trim().split(/\s+/).slice(0, 2)
      .map((part) => Array.from(part)[0] || "")
      .join("")
      .toLocaleUpperCase("sk-SK");
    avatar.textContent = initials;

    const personDetails = document.createElement("div");
    const name = document.createElement("h4");
    name.textContent = review.name.trim();

    const date = document.createElement("time");
    date.dateTime = review.date;
    const locale = activeLanguage === "uk" ? "uk-UA" : activeLanguage === "en" ? "en-GB" : "sk-SK";
    date.textContent = new Date(review.date).toLocaleDateString(locale, {
      day: "2-digit",
      month: "2-digit",
      year: "numeric",
    });
    personDetails.append(name, date);
    person.append(avatar, personDetails);

    const stars = document.createElement("span");
    stars.className = "review-stars";
    stars.setAttribute("role", "img");
    stars.setAttribute("aria-label", translate("reviews.starsAria", { rating: review.rating }));
    const starDisplay = document.createElement("span");
    starDisplay.setAttribute("aria-hidden", "true");
    starDisplay.textContent = `${"★".repeat(review.rating)}${"☆".repeat(5 - review.rating)}`;
    stars.append(starDisplay);
    header.append(person, stars);

    const quote = document.createElement("blockquote");
    const paragraph = document.createElement("p");
    paragraph.textContent = review.text.trim();
    quote.append(paragraph);
    card.append(header, quote);
    return card;
  };

  const formatReviewCount = (count) => {
    if (activeLanguage === "en") {
      return translate(count === 1 ? "reviews.countOne" : "reviews.count", { count });
    }
    if (activeLanguage === "uk") {
      const remainder = count % 10;
      const lastTwo = count % 100;
      const key = remainder === 1 && lastTwo !== 11
        ? "reviews.countOne"
        : remainder >= 2 && remainder <= 4 && (lastTwo < 12 || lastTwo > 14)
          ? "reviews.countFew"
          : "reviews.count";
      return translate(key, { count });
    }
    const key = count === 1 ? "reviews.countOne" : count >= 2 && count <= 4 ? "reviews.countFew" : "reviews.count";
    return translate(key, { count });
  };

  const updateRatingSummary = () => {
    const ratings = Array.from(reviewsGrid.querySelectorAll(".review-card"))
      .map((card) => Number(card.dataset.rating))
      .filter((rating) => Number.isInteger(rating) && rating >= 1 && rating <= 5);
    const count = ratings.length;
    const average = count ? ratings.reduce((total, rating) => total + rating, 0) / count : 0;
    const formattedAverage = average.toFixed(1);

    if (ratingScore) ratingScore.textContent = formattedAverage;
    if (ratingScoreStars) {
      ratingScoreStars.setAttribute(
        "aria-label",
        translate("reviews.starsAria", {
          rating: average.toLocaleString(activeLanguage === "uk" ? "uk-UA" : activeLanguage === "en" ? "en-GB" : "sk-SK", {
            minimumFractionDigits: 1,
            maximumFractionDigits: 1,
          }),
        }),
      );
    }
    if (ratingCountText) ratingCountText.textContent = translate("reviews.basedOn", { count });
    if (reviewsCountText) reviewsCountText.textContent = formatReviewCount(count);

    ratingRows.forEach((row) => {
      const rating = Number.parseInt(row.querySelector(".rating-level")?.textContent || "", 10);
      const percentage = count && rating >= 1 && rating <= 5
        ? Math.round((ratings.filter((value) => value === rating).length / count) * 100)
        : 0;
      const bar = row.querySelector(".rating-bar");
      const fill = bar?.querySelector("span");
      const percentText = row.querySelector(".rating-percent");

      if (bar) bar.setAttribute("aria-label", translate("reviews.percent", { percent: percentage }));
      if (fill) fill.style.width = `${percentage}%`;
      if (percentText) percentText.textContent = `${percentage}%`;
    });
  };
  refreshRating = updateRatingSummary;

  const updateReviewCardLabels = () => {
    reviewsGrid.querySelectorAll(".review-stars").forEach((stars) => {
      const card = stars.closest(".review-card");
      const rating = Number(card?.dataset.rating);
      if (Number.isInteger(rating)) {
        stars.setAttribute("aria-label", translate("reviews.starsAria", { rating }));
      }
    });
    reviewsGrid.querySelectorAll("time[datetime]").forEach((date) => {
      const locale = activeLanguage === "uk" ? "uk-UA" : activeLanguage === "en" ? "en-GB" : "sk-SK";
      const parsed = new Date(date.dateTime);
      date.textContent = parsed.toLocaleDateString(locale, {
        day: "2-digit",
        month: "2-digit",
        year: "numeric",
      });
    });
  };
  refreshReviewCards = updateReviewCardLabels;

  try {
    const storedReviews = localStorage.getItem(reviewsStorageKey);
    if (storedReviews) {
      const parsedReviews = JSON.parse(storedReviews);
      if (!Array.isArray(parsedReviews) || !parsedReviews.every(isReview)) {
        throw new Error("Uložené hodnotenia majú neplatný formát.");
      }
      parsedReviews.forEach((review) => reviewsGrid.append(createReviewCard(review)));
    }
  } catch {
    reviewStatusMessage = { key: "reviews.loadError" };
    reviewFormStatus.textContent = translate(reviewStatusMessage.key);
  }
  updateRatingSummary();

  if (
    nameInput instanceof HTMLInputElement
    && ratingSelect instanceof HTMLSelectElement
    && textInput instanceof HTMLTextAreaElement
  ) {
    reviewForm.addEventListener("submit", (event) => {
      event.preventDefault();
      if (!reviewForm.reportValidity()) return;

      const name = nameInput.value.trim();
      const text = textInput.value.trim();
      const rating = Number(ratingSelect.value);
      if (!name || !text || !Number.isInteger(rating) || rating < 1 || rating > 5) {
        reviewStatusMessage = { key: "reviews.invalid" };
        reviewFormStatus.textContent = translate(reviewStatusMessage.key);
        return;
      }

      const review = { name, rating, text, date: new Date().toISOString() };
      reviewsGrid.append(createReviewCard(review));
      updateRatingSummary();

      try {
        const storedReviews = localStorage.getItem(reviewsStorageKey);
        const parsedReviews = storedReviews ? JSON.parse(storedReviews) : [];
        if (!Array.isArray(parsedReviews) || !parsedReviews.every(isReview)) {
          throw new Error("Uložené hodnotenia majú neplatný formát.");
        }
        parsedReviews.push(review);
        localStorage.setItem(reviewsStorageKey, JSON.stringify(parsedReviews));
        reviewStatusMessage = { key: "reviews.saved" };
        reviewFormStatus.textContent = translate(reviewStatusMessage.key);
      } catch {
        reviewStatusMessage = { key: "reviews.notSaved" };
        reviewFormStatus.textContent = translate(reviewStatusMessage.key);
      }

      reviewForm.reset();
    });
  }

  refreshRating();
  updateReviewCardLabels();
}

const applyLanguage = (language) => {
  activeLanguage = language;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (key) element.textContent = translate(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (key && (element instanceof HTMLInputElement || element instanceof HTMLTextAreaElement)) {
      element.setAttribute("placeholder", translate(key));
    }
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (key && element instanceof HTMLImageElement) element.alt = translate(key);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (!key) return;

    let values = {};
    if (key === "cart.button") values = { count: getCartItemCount() };
    if (key === "menu.quantity") {
      const itemKey = element.dataset.menuKey;
      values = { name: itemKey ? translate(`menu.${itemKey}.name`) : "" };
    }
    if (key === "menu.decreaseQuantity" || key === "menu.increaseQuantity") {
      const itemKey = element.closest(".menu-card")?.dataset.menuKey;
      values = { name: itemKey ? translate(`menu.${itemKey}.name`) : "" };
    }
    element.setAttribute("aria-label", translate(key, values));
  });

  document.querySelectorAll(".language-option").forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (menuToggle) {
    const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-label", translate(isExpanded ? "navigation.close" : "navigation.open"));
  }
  if (lastReservation && reservationConfirmationTitle && reservationConfirmationDetails) {
    const guestLabel = reservationForm?.querySelector(`#reservation-guests option[value="${lastReservation.guestsValue}"]`)?.textContent?.trim() || "";
    const [year, month, day] = lastReservation.dateValue.split("-").map(Number);
    const locale = language === "uk" ? "uk-UA" : language === "en" ? "en-GB" : "sk-SK";
    const formattedDate = new Date(year, month - 1, day).toLocaleDateString(locale, {
      day: "numeric",
      month: "long",
      year: "numeric",
    });
    reservationConfirmationTitle.textContent = translate("reservation.thankYou", { name: lastReservation.name });
    reservationConfirmationDetails.textContent = translate("reservation.confirmation", {
      guests: guestLabel,
      date: formattedDate,
      time: lastReservation.time,
    });
  }

  refreshMenu();
  refreshCart();
  refreshRating();
  refreshReviewCards();
  if (cartStatus && cartStatusMessage) {
    cartStatus.textContent = translate(cartStatusMessage.key, cartStatusMessage.values);
  }
  if (reviewFormStatus && reviewStatusMessage) {
    reviewFormStatus.textContent = translate(reviewStatusMessage.key);
  }
  document.querySelectorAll(".rating-bar").forEach((bar) => {
    const percent = bar.querySelector("span")?.style.width || "0%";
    bar.setAttribute("aria-label", translate("reviews.percent", { percent: Number.parseFloat(percent) }));
  });

  try {
    localStorage.setItem(languageStorageKey, language);
  } catch (error) {
    console.error("Could not save the selected language.", error);
  }
};

document.querySelector(".language-switcher")?.addEventListener("click", (event) => {
  if (!(event.target instanceof Element)) return;
  const button = event.target.closest(".language-option");
  if (!(button instanceof HTMLButtonElement)) return;
  const language = button.dataset.language;
  if (language && supportedLanguages.includes(language)) applyLanguage(language);
});

